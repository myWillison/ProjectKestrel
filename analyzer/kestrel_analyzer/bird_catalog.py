CATALOG_PATH = MODELS_DIR / "birds" / "birds_global.csv"

# Region codes that ``Settings`` may legally store. Kept here -- not in
# ``settings_utils`` -- so the data layer owns the vocabulary and the
# settings sanitiser just imports it.
ALLOWED_REGION_CODES: tuple[str, ...] = (
    "NA", "MA", "SA", "AF", "PAL", "OR", "AU", "AN",
    "AO", "PO", "IO", "SO", "TrO", "Worldwide",
)

REGION_LABELS: dict[str, str] = {
    "NA":        "North America",
    "MA":        "Middle America & Caribbean",
    "SA":        "South America",
    "AF":        "Africa",
    "PAL":       "Eurasia (Palearctic)",
    "OR":        "South & SE Asia (Oriental)",
    "AU":        "Australasia",
    "AN":        "Antarctic",
    "AO":        "Atlantic Ocean",
    "PO":        "Pacific Ocean",
    "IO":        "Indian Ocean",
    "SO":        "Southern Ocean",
    "TrO":       "Tropical Oceans",
    "Worldwide": "Worldwide (cosmopolitan species)",
}

DEFAULT_REGION_SELECTION: tuple[str, ...] = ("NA",)

# Pseudo-region for "every IOC world species" (no geofence). Only meaningful
# for the species classifier's label space, never stored in ``regions``.
GLOBAL_REGION = "global"


def resolve_species_regions(value) -> list[str]:
    """Sanitise a species-geofence selection into a canonical list.

    Accepts a list/tuple (or a single code string). Returns ``["global"]`` if
    the selection contains ``"global"``; otherwise the valid region codes in
    ``ALLOWED_REGION_CODES`` order; falls back to ``DEFAULT_REGION_SELECTION``
    when nothing valid is left (``None``, empty, junk).
    """
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, (list, tuple, set, frozenset)):
        return list(DEFAULT_REGION_SELECTION)
    picked = {str(v).strip() for v in value if isinstance(v, str) and v.strip()}
    if any(v.lower() == GLOBAL_REGION for v in picked):
        return [GLOBAL_REGION]
    out = [code for code in ALLOWED_REGION_CODES if code in picked]
    return out or list(DEFAULT_REGION_SELECTION)


@dataclass(frozen=True)
class BirdRecord:
    canonical_common_name: str
    scientific_name: str
    family_sci: str
    family_common: str
    order: str
    regions: frozenset[str]
    alpha_4: str
    aliases: tuple[str, ...]
    is_model_species: bool
    # Display-only Chinese name from the overlay (see ``species_names``).
    # Empty when the overlay lacks the species or isn't shipped.
    zh_name: str = ""
    # Search-only companions from the same overlay (see ``name_search``):
    # the traditional spelling acts as an alias, pinyin is toned and one
    # syllable per character ("pǔ tōng cuì niǎo"), ebird_code is the eBird
    # species code ("comkin1").
    zh_name_traditional: str = ""
    pinyin: str = ""
    ebird_code: str = ""

    def matches_any_region(self, selected: frozenset[str]) -> bool:
        """True if at least one of ``regions`` is in ``selected``.

        A 'Worldwide' species always matches when *any* region is selected,
        because by definition it occurs across all the standard biogeographic
        regions and a user filtering down to (say) NA would still expect it
        in their list.
        """
        if not selected:
            return False
        if "Worldwide" in self.regions:
            return True
        return not selected.isdisjoint(self.regions)


@dataclass(frozen=True)
class FamilyEntry:
    family_common: str
    family_sci: str
    order: str
    regions: frozenset[str]
    # Display-only Chinese family name (empty when unmapped), plus the toned
    # pinyin derived for it (see ``species_names.char_pinyin_map``).
    family_zh: str = ""
    family_pinyin: str = ""

    def matches_any_region(self, selected: frozenset[str]) -> bool:
        if not selected:
            return False
        if "Worldwide" in self.regions:
            return True
        return not selected.isdisjoint(self.regions)


def _parse_regions(s: str) -> frozenset[str]:
    if not s:
        return frozenset()
    return frozenset(p for p in (t.strip() for t in s.split(",")) if p)


def _parse_aliases(s: str) -> tuple[str, ...]:
    if not s:
        return ()
    return tuple(p for p in (t.strip() for t in s.split("|")) if p)


def load_catalog(path: Path | None = None) -> list[BirdRecord]:
    """Read the bundled CSV. Skips header-equivalent or empty rows defensively."""
    p = Path(path) if path is not None else CATALOG_PATH
    zh_names = zh_species_info()
    out: list[BirdRecord] = []
    with open(p, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            name = (row.get("canonical_common_name") or "").strip()
            if not name:
                continue
            sci = (row.get("scientific_name") or "").strip()
            info = zh_names.get(normalize_scientific_name(sci))
            out.append(BirdRecord(
                canonical_common_name=name,
                scientific_name=sci,
                family_sci=(row.get("family_sci") or "").strip(),
                family_common=(row.get("family_common") or "").strip(),
                order=(row.get("order") or "").strip(),
                regions=_parse_regions(row.get("regions") or ""),
                alpha_4=(row.get("alpha_4") or "").strip().upper(),
                aliases=_parse_aliases(row.get("aliases") or ""),
                is_model_species=(row.get("is_model_species") or "").strip() == "1",
                zh_name=info.zh if info else "",
                zh_name_traditional=info.zh_traditional if info else "",
                pinyin=info.pinyin if info else "",
                ebird_code=info.ebird_code if info else "",
            ))
    return out



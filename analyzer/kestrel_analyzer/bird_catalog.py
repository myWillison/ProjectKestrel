"""Bundled global-bird catalog: regional filtering, fuzzy search, alpha-code lookup.

Loads ``analyzer/models/birds/birds_global.csv`` (generated by
``tools/build_bird_catalog.py``) and exposes a small query API used by the
API bridge to populate the species combobox.

The catalog is also the species classifier's label space: the BioCLIP head
(``ml/bioclip_species.py``) scores every row and geofences with the same
``matches_any_region`` rule the combobox uses, so a region fix here applies to
both. ``regions`` are IOC native breeding ranges plus the augmentation rules in
``tools/build_bird_catalog.py`` (``NA`` for every legacy model species, and a
curated list of established introductions such as House Sparrow).
"""

